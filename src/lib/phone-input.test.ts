import { describe, expect, it } from "vitest"
import { formatPhoneInput } from "./phone-input"

describe("formatPhoneInput", () => {
  it.each([
    ["", ""],
    ["07", "07"],
    ["0712", "0712"],
    ["07123", "0712 3"],
    ["0712345678", "0712 345 678"],
    ["0712 345 6789999", "0712 345 678"],
    ["0110345678", "0110 345 678"],
    ["+", "+"],
    ["+25", "+25"],
    ["+254", "+254"],
    ["+254712345678", "+254 712 345 678"],
    ["+2547123456789", "+254 712 345 678"],
    ["254712345678", "254 712 345 678"],
    ["712345678", "712 345 678"],
    ["7123456789", "712 345 678"],
    ["07a1-2", "0712"],
  ])("formats %j as %j", (input, expected) => {
    expect(formatPhoneInput(input)).toBe(expected)
  })
})
